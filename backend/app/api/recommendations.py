from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from sqlalchemy import desc
from typing import List, Optional
import datetime

from app.database.session import get_db
from app.models.models import Recommendation, Incident, User
from app.schemas.schemas import RecommendationOut, RecommendationAction
from app.api.deps import get_current_user

router = APIRouter(prefix="/recommendations", tags=["Smart Recommendations"])

@router.get("", response_model=List[RecommendationOut])
def list_recommendations(
    status: Optional[str] = Query(None, description="Filter by status (pending, applied, dismissed)"),
    priority: Optional[str] = Query(None, description="Filter by priority (urgent, high, medium, routine)"),
    db: Session = Depends(get_db)
):
    """Retrieve decision-support recommendations generated by Cross-System Intelligence."""
    query = db.query(Recommendation)
    if status and status != "all":
        query = query.filter(Recommendation.status == status)
    if priority and priority != "all":
        query = query.filter(Recommendation.priority == priority)

    return query.order_by(desc(Recommendation.created_at)).all()

@router.post("/{rec_id}/action", response_model=RecommendationOut)
def execute_recommendation_action(rec_id: int, action: RecommendationAction, db: Session = Depends(get_db)):
    """Apply or dismiss a recommendation."""
    rec = db.query(Recommendation).filter(Recommendation.id == rec_id).first()
    if not rec:
        raise HTTPException(status_code=404, detail="Recommendation not found")

    rec.status = action.status
    if action.status == "applied":
        rec.applied_at = datetime.datetime.now(datetime.timezone.utc)
    db.commit()
    db.refresh(rec)
    return rec

@router.post("/{rec_id}/convert-to-incident")
def convert_recommendation_to_incident(
    rec_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Convert an actionable smart recommendation into an official municipal incident ticket."""
    rec = db.query(Recommendation).filter(Recommendation.id == rec_id).first()
    if not rec:
        raise HTTPException(status_code=404, detail="Recommendation not found")

    now = datetime.datetime.now(datetime.timezone.utc)
    inc_num = f"INC-REC-{now.strftime('%Y%m%d')}-{now.strftime('%H%M%S')}"

    # Map priority to incident severity
    sev_map = {"urgent": "critical", "high": "high", "medium": "medium", "routine": "low"}
    sev = sev_map.get(rec.priority.lower(), "high")

    # Map category
    cat = "cross_system"
    if "traffic" in rec.sector.lower():
        cat = "traffic"
    elif "power" in rec.sector.lower() or "elec" in rec.sector.lower():
        cat = "electricity"
    elif "water" in rec.sector.lower():
        cat = "water"

    incident = Incident(
        incident_number=inc_num,
        title=f"[Recommendation Action] {rec.title}",
        category=cat,
        severity=sev,
        status="investigating",
        description=f"Actionable incident created from Recommendation #{rec.id}: {rec.what_happened}. Why it matters: {rec.why_it_matters}. Mitigation: {rec.suggested_action}",
        location_name=rec.affected_infrastructure,
        sector=rec.sector,
        assigned_department=rec.sector or "Municipal Rapid Response",
        reported_by=current_user.full_name or "CITYSYNC Recommendation Engine",
        created_at=now,
        updated_at=now
    )
    db.add(incident)

    # Mark recommendation as applied
    rec.status = "applied"
    rec.applied_at = now

    db.commit()
    db.refresh(incident)

    return {
        "message": f"Recommendation #{rec.id} converted into Incident {inc_num}",
        "incident_number": inc_num,
        "incident_id": incident.id,
        "recommendation_id": rec.id
    }

